export const SCENES: Scene[] = SCENES_INPUT.map((s) => scene.parse(s));

export function getScene(id: string | null | undefined): Scene | null {
  return id ? SCENES.find((s) => s.id === id || s.slug === id) ?? null : null;
}

/** Cenas agrupadas pela região temática (catálogo do estúdio). */
export function scenesForRegion(region: Scene["region"]) {
  return SCENES.filter((s) => s.region === region);
}

/** Cenas que usam um modelo (página de uma região no atlas carrega um modelo só). */
export function scenesForModel(modelId: string) {
  return SCENES.filter((s) => s.modelId === modelId);
}
